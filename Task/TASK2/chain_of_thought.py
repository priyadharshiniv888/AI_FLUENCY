def chain_of_thought(question):
    print("CHAIN-OF-THOUGHT")
    print("----------------")

    print("Question:", question)

    print("Step 1: Identify the number of students.")
    print("Step 2: Identify the budget per student.")
    print("Step 3: Multiply students by budget per student.")
    print("Final Answer: Rs.4500")


question = "Three students have Rs.1500 each. What is their total trip budget?"

chain_of_thought(question)